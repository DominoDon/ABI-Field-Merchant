// Regenerates data.js (the built-in game data) from abibuilder.com/merchant.
// Usage: node tools/gen-data.js            (fetches the page)
//        node tools/gen-data.js page.html  (uses a saved copy)
// The parsing lives in merchantData.js, shared with the app's automatic data updates.
const fs = require('fs');
const path = require('path');
const https = require('https');

function loadModule(file) {
  // merchantData.js is an ES module for the browser; load its exports here without a bundler
  const src = fs.readFileSync(file, 'utf8').replace(/^export\s+(function|const)\s+/gm, '$1 ');
  const names = [...src.matchAll(/^function\s+(\w+)/gm)].map(m => m[1]);
  return new Function(`${src}\nreturn { ${names.join(', ')} };`)();
}

function fetchPage() {
  return new Promise((resolve, reject) => {
    https.get('https://abibuilder.com/merchant', { headers: { 'User-Agent': 'Mozilla/5.0' } }, res => {
      let d = '';
      res.setEncoding('utf8');
      res.on('data', c => (d += c));
      res.on('end', () => resolve(d));
    }).on('error', reject);
  });
}

(async () => {
  const M = loadModule(path.join(__dirname, '..', 'merchantData.js'));
  const html = process.argv[2] ? fs.readFileSync(process.argv[2], 'utf8') : await fetchPage();
  const data = M.extractMerchantData(html, new Date().toISOString().slice(0, 10));
  const problem = M.validateGameData(data);
  if (problem) throw new Error('Data looks wrong: ' + problem);
  const out = `// Arena Breakout: Infinite - Field Merchant data (generated by tools/gen-data.js - do not edit by hand)
// Source: abibuilder.com/merchant. The app refreshes this automatically at runtime (merchantData.js).
// rarity: 1 white, 2 green, 3 blue, 4 purple, 5 gold, 6 red. value = contact (hand-in) price, market = market reference price, in Koen.
// pools: one cargo loot group; a crate (profile + typeId + price) rolls a group by weight, then an item by weight.
export const GAME_DATA = ${JSON.stringify(data)};
`;
  fs.writeFileSync(path.join(__dirname, '..', 'data.js'), out, 'utf8');
  console.log(`data.js written: ${data.sounds.length} sounds, ${data.items.length} items, ${data.profiles.length} map groups, ${data.pools.length} pools, ${(out.length / 1024).toFixed(0)} KB`);
})().catch(e => { console.error(e.message); process.exit(1); });
